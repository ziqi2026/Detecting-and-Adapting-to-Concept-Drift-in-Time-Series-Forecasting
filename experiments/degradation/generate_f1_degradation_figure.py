def load_rolling_mae():
    """
    Load and validate the saved F1 rolling-MAE source file.
    """

    if not INPUT_PATH.exists():
        raise FileNotFoundError(
            f"Cannot find {INPUT_PATH}. "
            "Run run_baseline_degradation_evaluation.py first."
        )

    data = pd.read_csv(
        INPUT_PATH
    )

    required = {
        "SETTLEMENTDATE",
        "region",
        "method",
        "rolling_mae",
    }

    missing = (
        required
        - set(data.columns)
    )

    if missing:
        raise ValueError(
            "F1 rolling-MAE file is missing columns: "
            f"{sorted(missing)}"
        )

    data["SETTLEMENTDATE"] = pd.to_datetime(
        data["SETTLEMENTDATE"]
    )

    return data


def add_event_markers(
    ax,
    region,
):
    """
    Add documented AEMO events to one F1 figure.

    Single-day events are shown with dashed vertical lines.

    Multi-day events are shown as shaded windows with a dashed
    line marking the documented start.
    """

    for event in EVENTS[region]:

        event_start = pd.Timestamp(
            event["start"]
        )

        event_end = pd.Timestamp(
            event["end"]
        )

        if event_start == event_end:

            ax.axvline(
                event_start,
                linestyle="--",
                linewidth=1.0,
                alpha=0.7,
            )

            label_time = event_start

        else:

            event_end_exclusive = (
                event_end
                + pd.Timedelta(days=1)
            )

            ax.axvspan(
                event_start,
                event_end_exclusive,
                alpha=0.08,
            )

            ax.axvline(
                event_start,
                linestyle="--",
                linewidth=1.0,
                alpha=0.7,
            )

            label_time = (
                event_start
                + (
                    event_end_exclusive
                    - event_start
                )
                / 2
            )

        ax.text(
            label_time,
            0.98,
            event["label"],
            transform=ax.get_xaxis_transform(),
            rotation=90,
            verticalalignment="top",
            horizontalalignment="right",
            fontsize=8,
        )

def make_region_figure(
    data,
    region,
):
    """
    Generate F1 baseline degradation figure for one AEMO region.
    """

    region_data = data[
        data["region"] == region
    ].copy()

    if region_data.empty:
        raise ValueError(
            f"No rolling-MAE data found for region {region}."
        )

    fig, ax = plt.subplots(
        figsize=(18, 8)
    )

    for method in MODEL_ORDER:

        method_data = region_data[
            region_data["method"] == method
        ].copy()

        if method_data.empty:
            raise ValueError(
                f"No data found for {region} | {method}."
            )

        method_data = (
            method_data
            .sort_values(
                "SETTLEMENTDATE"
            )
        )

        ax.plot(
            method_data["SETTLEMENTDATE"],
            method_data["rolling_mae"],
            linewidth=1.4,
            label=MODEL_LABELS[method],
        )

    add_event_markers(
        ax,
        region,
    )

    ax.set_title(
        f"F1 — Frozen Baseline Degradation Curve: {region}",
        fontsize=16,
        pad=14,
    )

    ax.set_xlabel(
        "Date",
        fontsize=13,
    )

    ax.set_ylabel(
        "7-day rolling MAE (MW)",
        fontsize=13,
    )

    ax.tick_params(
        axis="both",
        labelsize=11,
    )

    ax.grid(
        alpha=0.2
    )

    ax.legend(
        loc="upper left",
        bbox_to_anchor=(1.01, 1.0),
        borderaxespad=0.0,
        fontsize=11,
        title="Baseline model",
        title_fontsize=11,
    )

    caption = (
        f"F1. {ROLLING_WINDOW_DAYS}-day rolling MAE "
        f"({ROLLING_WINDOW} half-hourly observations) of the "
        f"three frozen baseline forecasting models over the "
        f"AEMO {region} test stream. "
        f"Single-day documented events are marked by dashed lines; "
        f"multi-day documented events are shown as shaded periods."
    )

    fig.text(
        0.5,
        0.035,
        caption,
        ha="center",
        va="bottom",
        fontsize=12,
        wrap=True,
    )

    fig.subplots_adjust(
        left=0.07,
        right=0.82,
        top=0.90,
        bottom=0.18,
    )

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = (
        OUTPUT_DIR
        / f"F1_{region}_baseline_degradation.png"
    )

    fig.savefig(
        output_path,
        dpi=180,
        bbox_inches="tight",
    )

    plt.close(
        fig
    )

    print(
        f"Saved: {output_path}"
    )

def main():

    print(
        "Generating F1 baseline degradation figures"
    )

    print(
        f"Rolling MAE window: "
        f"{ROLLING_WINDOW_DAYS} days "
        f"({ROLLING_WINDOW} half-hourly observations)"
    )

    print(
        "Models are not retrained."
    )

    print(
        "No metrics will be written to runs.csv."
    )

    data = load_rolling_mae()

    for region in (
        "SA1",
        "NSW1",
    ):

        make_region_figure(
            data,
            region,
        )

    print(
        "F1 figure generation complete."
    )


if __name__ == "__main__":
    main()