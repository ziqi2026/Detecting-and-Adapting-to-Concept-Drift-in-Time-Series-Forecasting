"""
Generate F1 forecasting-degradation figures from saved rolling-MAE results.

This script reads the timestamp-level rolling-MAE source generated by:

    experiments/degradation/run_baseline_degradation_evaluation.py

The source file may contain the three required project baselines:

    - Seasonal Naive
    - SARIMAX
    - Gradient Boosting

and any additional forecasting models that were active when the
degradation experiment was run, such as PatchTST.

PatchTST depends on the optional PyTorch package. If PyTorch was
available during the degradation run, PatchTST results may be present
in the saved source. If PyTorch was unavailable, the saved source
contains only the models that were registered in that environment.

This figure script does not require PyTorch itself. It plots the models
actually present in the saved result file.

All available methods in the saved result file are plotted. Models
registered in MODEL_REGISTRY follow registry order; any additional
methods found in an older or external result file are appended rather
than discarded.


INPUT
-----
results/tables/degradation/F1_rolling_mae.csv

Required columns:

    - SETTLEMENTDATE
    - region
    - method
    - rolling_mae


OUTPUTS
-------
results/figures/degradation/F1_SA1_forecasting_degradation.png
results/figures/degradation/F1_NSW1_forecasting_degradation.png

Each figure shows:

    - 7-day rolling MAE for every available forecasting model
    - documented AEMO contextual events
    - single-day events as dashed vertical lines
    - multi-day events as shaded intervals
    - a forecasting-model legend
    - the rolling-window definition in the caption


FIGURE-ONLY PROTOCOL
--------------------
This script performs visualization only.

It:

    - does not fit forecasting models
    - does not retrain forecasting models
    - does not recompute MAE
    - does not modify results/runs.csv

All forecasting and rolling-MAE calculations must already have been
completed by the degradation experiment before this script is run.

The figure reflects the methods stored in the saved rolling-MAE source,
regardless of whether their runtime dependencies are currently
installed.

Documented AEMO events are shown as contextual reference points and
are not treated as ground-truth concept-drift changepoints.
"""

