"""
Drift detector implementation following the frozen interface defined in
interfaces.py

detector(stream) ---> changepoint
indices

Input: Frozen error stream
Detectors connect directly with
pipeline via drift_lab.forecasters.frozen_error_stream(), rather than
creating a separate workflow. frozen_error_stream() returns a
chronologically ordered stream with columns:

    SETTLEMENTDATE, y_true, y_pred, error
"""

import numpy as np
import pandas as pd

# Detectors
from river.drift import ADWIN, PageHinkley, KSWIN

# Forecaster
from drift_lab.forecasters import frozen_error_stream


def get_error_stream(model, test: pd.DataFrame, history_df: pd.DataFrame):
    """chronological error series out of frozen_error_stream()"""
    error_df = frozen_error_stream(model, test, history_df=history_df)

    required_cols = {"SETTLEMENTDATE", "y_true", "y_pred", "error"}
    missing = required_cols - set(error_df.columns)
    if missing:
        raise ValueError(f"frozen_error_stream() output is missing required columns: {missing}")

    error_df = error_df.sort_values("SETTLEMENTDATE").reset_index(drop=True)
    return error_df["error"].to_numpy(dtype=float)

def run_detectors(stream, det):
  """Feed a detector one observation at a time
  and collect alarms indices"""
  stream = np.asarray(stream,dtype=float)
  changepoints:list[int] = []
  for t, x in enumerate(stream):
    det.update(x)
    if det.drift_detected:
      changepoints.append(int(t))
  return changepoints

def detector_page_hinkley(stream, delta=0.005, threshold=50, alpha=0.9999):

  return run_detectors(stream,PageHinkley(delta=delta,threshold=threshold, alpha=alpha))

def detector_adwin(stream, delta=0.002):

  return run_detectors(stream, ADWIN(delta=delta))

def detector_kswin(stream, alpha=0.005, window_size=100, stat_size=30, seed=12):

  return run_detectors(stream, KSWIN(alpha=alpha, window_size=window_size, stat_size=stat_size, seed=seed))


DETECTOR_REGISTRY = {
    "page_hinkley": {"func": detector_page_hinkley, "config": {"delta": 0.005, "threshold": 50, "alpha": 0.9999}},
    "adwin": {"func": detector_adwin, "config": {"delta": 0.002}},
    "kswin": {"func": detector_kswin, "config": {"alpha": 0.005, "window_size": 100, "stat_size": 30, "seed": 12}},
}


def run_all_detectors(stream):
    """Run every detector on the same stream"""
    results = {}
    for name, entry in DETECTOR_REGISTRY.items():
        results[name] = {"changepoints": entry["func"](stream), "config": entry["config"]}
    return results